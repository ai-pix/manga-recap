import json
import urllib.request
from pathlib import Path

desc_path = Path("data/chapters/barbarian_ch02/03_descriptions.json")
summary_path = Path("data/chapters/barbarian_ch02/03_summary_mercury.txt")
desc = json.loads(desc_path.read_text(encoding="utf-8"))
summary = summary_path.read_text(encoding="utf-8")

panels = desc["panels"]
# Format panel list
panel_lines = []
for p in panels:
    pid = p["panel_id"]
    if p.get("is_credits_or_ad"):
        continue
    act = p.get("action", "")
    speech = " | ".join(p.get("speech_bubbles", []))
    panel_lines.append(f"- {pid}: Action: {act} | Speech: {speech}")

panels_text = "\n".join(panel_lines)

prompt = f"""You are an elite YouTube manhwa recap writer (style: Mamoru Manhwa).
You are writing 04_script.json for Chapter 2 of 'Surviving the Game as a Barbarian'.

Here is the narrative summary generated by Mercury 2.5:
\"\"\"
{summary}
\"\"\"

Here are the exact panel descriptions that MUST be covered in order:
\"\"\"
{panels_text}
\"\"\"

STRICT RULES:
1. Every non-skippable panel must be mapped to a block in reading order (1:1 mapping where each block has exactly 1 panel_id, or multi-panel beats when natural).
2. For each block, provide:
   - block_id: b001, b002, ...
   - panel_ids: ["panel_XXXX"]
   - narration: 1-2 punchy, spoken recap sentences (8-18 words).
   - direction: "beat"
   - beats: [] (or explicit clauses if multi-panel or complex)
3. ZERO TOLERANCE VOCABULARY BANS: NEVER use 'panel', 'panels', 'chapter', 'page', 'manga', 'manhwa', 'author', 'artist', 'reader', 'viewers'.
4. Character names: Bjorn (Hansoo), Aynar, Karaq, Elder.
5. Tone: Energetic, witty, analytical RPG gamer perspective.

Return ONLY valid JSON matching this schema:
{{
  "chapter_id": "barbarian_ch02",
  "title": "Chapter 2: The Shield of Survival",
  "series": "barbarian",
  "created_at": "2026-10-06T22:45:00",
  "model": "inception/mercury-2.5",
  "target_words": 1800,
  "blocks": [
    {{
      "block_id": "b001",
      "panel_ids": ["panel_0001"],
      "narration": "...",
      "direction": "beat",
      "beats": []
    }}
  ]
}}
"""

payload = {
    "model": "inception/mercury-2.5",
    "messages": [{"role": "user", "content": prompt}],
    "max_tokens": 12000,
    "reasoning": {"max_tokens": 0},
    "response_format": {"type": "json_object"},
}

